import type { IndicatorId } from '../../simulation/state/indicators';
import type { BillType, BlocId, GroupId, OpinionFactor, OrgId, RegionId, WorldState } from '../../simulation/state/types';

export type Instrumento = BillType | 'decreto' | 'ato_gestao';

export type PolicyEffect =
  | { kind: 'ind'; ind: IndicatorId; porMes: number; defasagem: number; nota: string; saturaEm?: number }
  | { kind: 'ind_unico'; ind: IndicatorId; valor: number; defasagem: number; nota: string }
  | { kind: 'opiniao'; factor: OpinionFactor; grupos: Partial<Record<GroupId, number>>; defasagem: number; nota: string }
  | { kind: 'alavanca'; alavanca: 'fedTaxa' | 'icmsNivel' | 'petrobrasAjuste'; valor: number; nota: string }
  | { kind: 'governadores'; delta: number; regioes?: Partial<Record<RegionId, number>>; nota: string }
  | { kind: 'receita'; porMes: number; nota: string }
  | { kind: 'inflacao_direta'; porMes: number; meses: number; nota: string };

export interface PolicyDef {
  id: string;
  nome: string;
  resumo: string;
  objetivo: string;
  problema: string;
  populacaoAlvo: string;
  orgao: OrgId;
  instrumentos: { tipo: Instrumento; descricao: string }[];
  /** Casa iniciadora (PEC de autoria parlamentar já em tramitação). */
  casaInicial?: 'camara' | 'senado';
  custoImplantacao: number; // R$ bi
  custoMensal: number; // R$ bi/mês em execução
  renunciaMensal: number; // R$ bi/mês de receita perdida
  financiamento: 'discricionario' | 'obrigatoria_teto' | 'excecao_teto' | 'renuncia' | 'nenhum';
  /** Meses entre aprovação/edição e início da execução. */
  preparacao: number;
  /** Mês civil (ISO 'AAAA-MM') em que a política termina, se temporária. */
  fim?: string;
  /** Mês mínimo de início (ex.: reajuste a partir de julho). */
  inicioMinimo?: string;
  /** Duração máxima em meses (para alavancas temporárias). */
  duracao?: number;
  complexidade: number; // 0..1 — sensibilidade à capacidade administrativa
  exigeCooperacaoEstadual: boolean;
  /** Fração executada via transferências voluntárias (vedadas jul–out). */
  viaTransferenciaVoluntaria?: number;
  /** Fração afetada pela vedação de contratações (jul–dez). */
  dependeContratacao?: number;
  multiplicadorDemanda: number;
  efeitos: PolicyEffect[];
  aoAnunciar?: { ind: IndicatorId; valor: number; nota: string }[];
  aoAprovar?: { ind: IndicatorId; valor: number; nota: string }[];
  beneficiados: string;
  prejudicados: string;
  distribuicao: string;
  afinidade: Record<BlocId, number>;
  ajusteSenado?: number;
  popularidade: number; // -1..1
  importancia: 1 | 2 | 3;
  riscoJudicial: number; // chance de contestação ao entrar em vigor
  fragilidadeJuridica: number; // chance-base de liminar se contestada
  autorContestacao: string;
  fundamentoContestacao: string;
  ajusteTexto: { descricao: string; eficacia: number; custoFator: number; alivioFederativo?: number; afinidadeExtra: Partial<Record<BlocId, number>> };
  incertezas: string[];
  dependencias: string[];
  evidencia: string;
  abstracao: string;
  historico: string;
  especial?: 'excecao_teto' | 'reajuste' | 'reforma_tributaria';
  restricao?: (s: WorldState, instrumento: Instrumento) => string | null;
  /** Política já em tramitação no início (não lançável pelo jogador). */
  inicial?: boolean;
}

